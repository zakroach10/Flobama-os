export function ecammEndpointByName(name: string): EcammEndpointDef | undefined {
  return ECAMM_ENDPOINTS.find((e) => e.name === name);
}

export function ecammEndpointCoverageCounts() {
  const total = ECAMM_ENDPOINTS.length;
  const byStatus = ECAMM_ENDPOINTS.reduce(
    (acc, e) => {
      acc[e.status] = (acc[e.status] ?? 0) + 1;
      return acc;
    },
    {} as Record<string, number>,
  );
  const reads = ECAMM_ENDPOINTS.filter((e) => e.kind === "read").length;
  const actions = ECAMM_ENDPOINTS.filter((e) => e.kind !== "read").length;
  return { total, reads, actions, byStatus };
}

